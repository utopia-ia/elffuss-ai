// Writes deploy/nginx/ from deploy/headers.mjs and deploy/sites.mjs: one vhost
// per host (and a port-80-only version for the first certificate), one headers
// snippet per site that includes a common one, and the shared http-level file.
//
//   node deploy/build-nginx.mjs            write
//   node deploy/build-nginx.mjs --check    compare with what is committed (exit 1 on any difference)
//   ELFFUSS_NGINX=<nginx binary> node deploy/build-nginx.mjs --nginx-test
//                                          run `nginx -t` on the generated files in a scratch
//                                          prefix, with a throwaway certificate (never on a server)
import { readFileSync, writeFileSync, mkdirSync, existsSync, mkdtempSync, rmSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { sites as readSites } from './sites.mjs';
import { commonHeaders, csp, permissionsPolicy, CACHE, TYPES } from './headers.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'deploy', 'nginx');
const HEAD = '# GENERATED by deploy/build-nginx.mjs from deploy/headers.mjs. Do not edit.\n';
const q = v => `"${String(v).replace(/"/g, '\\"')}"`;

const typesBlock = exts => {
  const byType = new Map();
  for (const e of exts) {
    const t = TYPES[e];
    if (!t) throw new Error('no type for .' + e);
    byType.set(t, [...(byType.get(t) || []), e]);
  }
  return `types { ${[...byType].map(([t, es]) => `${t.replace(/; charset=utf-8$/, '')} ${es.join(' ')};`).join(' ')} }`;
};

/** The http-level file shared by every site. */
export function confD() {
  return `${HEAD}# /etc/nginx/conf.d/elffuss-ai.conf (http context)
limit_conn_zone $binary_remote_addr zone=elffuss_ai_conn:10m;
log_format elffuss_ai '$host $remote_addr [$time_local] "$request" $status $body_bytes_sent "$http_referer" "$http_user_agent"';
`;
}

/** Headers every location of every site carries. */
export function commonSnippet() {
  return HEAD + commonHeaders().map(([k, v]) => `add_header ${k} ${q(v)} always;`).join('\n') + '\n';
}

/** Headers of one site: the common ones, its CSP and its Permissions-Policy. */
export function siteSnippet(site) {
  return `${HEAD}include snippets/elffuss-ai-common-headers.conf;
add_header Content-Security-Policy ${q(csp(site))} always;
add_header Permissions-Policy ${q(permissionsPolicy(site))} always;
`;
}

/** The vhost of a site. With `port80Only`, just the block that serves the ACME challenge and redirects. */
export function vhost(site, { port80Only = false } = {}) {
  const h = site.host;
  const snip = `include snippets/elffuss-ai-${site.site}-headers.conf;`;
  const http = `server {
    listen 80;
    listen [::]:80;
    server_name ${h};
    location ^~ /.well-known/acme-challenge/ { root /var/www/letsencrypt; default_type text/plain; }
    location / { return 301 https://${h}$request_uri; }
}
`;
  if (port80Only) return `${HEAD}# /etc/nginx/sites-available/${h}.80.conf: first step, before the certificate exists.\n${http}`;
  const vendor = site.catalog ? '' : `
    # Vendored runtimes: the version is in the path.
    location ^~ /vendor/ {
        ${snip}
        add_header Cache-Control ${q(CACHE.vendor)} always;
        ${typesBlock(['js', 'mjs', 'wasm', 'json', 'txt', 'bcmap', 'pfb', 'ttf', 'icc'])}
        default_type text/plain;
        open_file_cache max=200 inactive=10m;
        try_files $uri =404;
    }`;
  return `${HEAD}# /etc/nginx/sites-available/${h}.conf
${http}server {
    listen 443 ssl;
    listen [::]:443 ssl;
    server_name ${h};
    ssl_certificate     /etc/letsencrypt/live/${h}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/${h}/privkey.pem;
    # TLS options: copy the include the existing vhosts of the server use (not verified here).
    root /var/www/${h}/site;
    index index.html;
    autoindex off;
    charset utf-8;
    access_log /var/log/nginx/${h}.access.log elffuss_ai;
    error_log  /var/log/nginx/${h}.error.log;
    limit_conn elffuss_ai_conn 16;
    default_type application/octet-stream;
    error_page 404 /404.html;

    # Pages: always revalidated.
    location / {
        ${snip}
        add_header Cache-Control ${q(CACHE.html)} always;
        ${typesBlock(['html', 'txt'])}
        try_files $uri $uri/ =404;
    }
    # Files of a build: they never change.
    location ^~ /v/ {
        ${snip}
        add_header Cache-Control ${q(CACHE.v)} always;
        ${typesBlock(['js', 'mjs', 'css', 'json', 'svg', 'png', 'txt'])}
        try_files $uri =404;
    }${vendor}
    # PRE: the same site under /beta/, not indexed.
    location /beta/ {
        ${snip}
        add_header Cache-Control ${q(CACHE.beta)} always;
        add_header X-Robots-Tag "noindex" always;
        ${typesBlock(['html'])}
        try_files $uri $uri/ =404;
    }
}
`;
}

/** Every generated file, path relative to deploy/nginx/ → content. */
export function generate(root = ROOT) {
  const files = new Map();
  files.set('conf.d/elffuss-ai.conf', confD());
  files.set('snippets/elffuss-ai-common-headers.conf', commonSnippet());
  for (const s of readSites(root)) {
    files.set(`snippets/elffuss-ai-${s.site}-headers.conf`, siteSnippet(s));
    files.set(`sites-available/${s.host}.conf`, vhost(s));
    files.set(`sites-available/${s.host}.80.conf`, vhost(s, { port80Only: true }));
  }
  return files;
}

function listFiles(dir, base = dir) {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...listFiles(p, base));
    else out.push(p.slice(base.length + 1));
  }
  return out;
}

/** Problems between the generated files and deploy/nginx/ (empty when equal). */
export function check() {
  const files = generate();
  const problems = [];
  for (const [p, text] of files) {
    const f = join(OUT, p);
    if (!existsSync(f)) problems.push(`${p}: missing`);
    else if (readFileSync(f, 'utf8') !== text) problems.push(`${p}: differs from deploy/headers.mjs`);
  }
  for (const p of listFiles(OUT)) if (!files.has(p) && !p.includes('/._') && !p.startsWith('._')) problems.push(`${p}: not generated`);
  return problems;
}

/** `nginx -t` on the generated files, in a scratch prefix with a throwaway certificate. */
function nginxTest(bin) {
  const tmp = mkdtempSync(join(tmpdir(), 'nginx-test-'));
  try {
    for (const d of ['conf.d', 'snippets', 'sites-enabled', 'tls', 'logs', 'www']) mkdirSync(join(tmp, d), { recursive: true });
    execFileSync('openssl', ['req', '-x509', '-newkey', 'ec', '-pkeyopt', 'ec_paramgen_curve:prime256v1', '-nodes', '-keyout', join(tmp, 'tls', 'key.pem'), '-out', join(tmp, 'tls', 'cert.pem'), '-days', '1', '-subj', '/CN=test'], { stdio: 'ignore' });
    for (const [p, text] of generate()) {
      let t = text.replace(/\/etc\/letsencrypt\/live\/[^/]+\/fullchain\.pem/g, join(tmp, 'tls', 'cert.pem'))
        .replace(/\/etc\/letsencrypt\/live\/[^/]+\/privkey\.pem/g, join(tmp, 'tls', 'key.pem'))
        .replace(/\/var\/log\/nginx\//g, join(tmp, 'logs') + '/')
        .replace(/listen (\[::\]:)?(80|443)/g, (m, v6, port) => `listen ${v6 || '127.0.0.1:'}${port === '80' ? 18080 : 18443}`);
      if (p.startsWith('sites-available/')) { if (p.endsWith('.80.conf')) continue; writeFileSync(join(tmp, 'sites-enabled', p.slice('sites-available/'.length)), t.replace(/^\s*listen \[::\].*\n/gm, '')); }
      else writeFileSync(join(tmp, p), t);
    }
    writeFileSync(join(tmp, 'nginx.conf'), `pid ${join(tmp, 'nginx.pid')};\nerror_log ${join(tmp, 'logs', 'error.log')};\nevents {}\nhttp {\n  include ${join(tmp, 'conf.d')}/*.conf;\n  include ${join(tmp, 'sites-enabled')}/*.conf;\n}\n`);
    execFileSync(bin, ['-t', '-p', tmp, '-c', join(tmp, 'nginx.conf')], { stdio: 'inherit', cwd: tmp });
    return 0;
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}

function main(argv) {
  if (argv.includes('--check')) {
    const problems = check();
    for (const p of problems) console.log('✗ ' + p);
    console.log(problems.length ? `nginx: ${problems.length} problems (run node deploy/build-nginx.mjs)` : 'nginx: deploy/nginx/ matches deploy/headers.mjs');
    return problems.length ? 1 : 0;
  }
  if (argv.includes('--nginx-test')) {
    const bin = process.env.ELFFUSS_NGINX;
    if (!bin) { console.error('set ELFFUSS_NGINX to an nginx binary'); return 2; }
    return nginxTest(bin);
  }
  rmSync(OUT, { recursive: true, force: true });
  for (const [p, text] of generate()) {
    mkdirSync(dirname(join(OUT, p)), { recursive: true });
    writeFileSync(join(OUT, p), text);
  }
  console.log(`nginx: ${generate().size} files written to deploy/nginx/`);
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exitCode = main(process.argv.slice(2));
