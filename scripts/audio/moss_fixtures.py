# Reference data for the MOSS-TTS-Nano speech of sdk/audio, made with the official
# ONNX runtime of OpenMOSS/MOSS-TTS-Nano (onnx_tts_runtime.py, onnxruntime on the
# CPU) and the ONNX files of the pinned revisions:
#
#   python moss_fixtures.py <dir with MOSS-TTS-Nano-100M-ONNX and MOSS-Audio-Tokenizer-Nano-ONNX>
#                           <reference voice .wav> <voice name> <out dir of sdk/audio> <out dir of tests/fixtures/audio>
#
# It writes:
#   sdk/audio/moss-voice-<name>.js   the codes of the reference voice (the voice prompt), so the
#                                    browser never encodes audio;
#   tests/fixtures/audio/moss-spm-ids.json  SentencePiece ids of tokenizer.model for test strings;
#   tests/fixtures/audio/moss-frames.json   the request rows of a sentence and the first frames
#                                    the model samples with the uniform numbers of sdk/audio/rng.js
#                                    (createRng(seed).uniform), the same draw order as the JS side.
import sys, json, hashlib
import numpy as np
from onnx_tts_runtime import OnnxTtsRuntime

onnx_dir, ref_wav, name, sdk_out, fix_out = sys.argv[1:6]
rt = OnnxTtsRuntime(model_dir=onnx_dir, thread_count=4)


def splitmix32(seed):
    s = seed & 0xFFFFFFFF
    def nxt():
        nonlocal s
        s = (s + 0x9E3779B9) & 0xFFFFFFFF
        z = s
        z = ((z ^ (z >> 16)) * 0x85EBCA6B) & 0xFFFFFFFF
        z = ((z ^ (z >> 13)) * 0xC2B2AE35) & 0xFFFFFFFF
        return (z ^ (z >> 16)) & 0xFFFFFFFF
    return nxt


class Xoshiro:
    """sdk/audio/rng.js createRng(seed).uniform(): xoshiro128** seeded by splitmix32."""
    def __init__(self, seed):
        sm = splitmix32(seed)
        self.a, self.b, self.c, self.d = sm(), sm(), sm(), sm()
        if not (self.a | self.b | self.c | self.d):
            self.a = 1
    def random(self):
        a, b, c, d = self.a, self.b, self.c, self.d
        m = (b * 5) & 0xFFFFFFFF
        r = ((((m << 7) | (m >> 25)) & 0xFFFFFFFF) * 9) & 0xFFFFFFFF
        t = (b << 9) & 0xFFFFFFFF
        c ^= a; d ^= b; b ^= c; a ^= d; c ^= t
        d = ((d << 11) | (d >> 21)) & 0xFFFFFFFF
        self.a, self.b, self.c, self.d = a, b, c, d
        return r / 4294967296


# 1. The voice prompt.
codes = rt.encode_reference_audio(ref_wav)
wav_sha = hashlib.sha256(open(ref_wav, 'rb').read()).hexdigest()
with open(f'{sdk_out}/moss-voice-{name}.js', 'w') as f:
    f.write('// SPDX-License-Identifier: Apache-2.0\n// Copyright (c) 2026 UtopiaIA\n//\n')
    f.write('// GENERATED by scripts/audio/moss_fixtures.py. Do not edit.\n//\n')
    f.write(f'// The voice prompt of MOSS-TTS-Nano for the voice "{name}": the codes that\n')
    f.write('// MOSS-Audio-Tokenizer-Nano (moss_audio_tokenizer_encode.onnx) gives for its reference\n')
    f.write(f'// recording (sha256 {wav_sha}), {len(codes)} frames of 16 codes (12.5 frames a second).\n')
    f.write('// The recording is a synthetic voice (see NOTICE), not the voice of a person.\n\n')
    f.write(f'export const FRAMES = {len(codes)};\n')
    f.write('/** Frame-major codes: FRAMES × 16. */\n')
    f.write('export const CODES = Object.freeze(' + json.dumps([c for row in codes for c in row]) + ');\n')
print('voice frames', len(codes))

# 2. SentencePiece ids.
strings = [
    'Hola, soy Elffuss. Hoy hace un día estupendo en Zaragoza: vamos a cocinar una paella con cebolla, ajo y azafrán. ¿Te apetece probarla?',
    'Cuando quieras, te cuento un cuento antes de dormir. Había una vez una ciudad pequeña junto al mar, donde las gaviotas cantaban al amanecer.',
    'Gracias por venir. ¿Te hace un zumo de naranja o prefieres un café con azúcar? Cerca de aquí hay una plaza preciosa.',
    '¡Qué bien! Ñandú, pingüino, cigüeña y año: 1.234,56 € el 3/11/2026.',
    '  dos   espacios  y\ttabulador  ',
    'The quick brown fox jumps over the lazy dog.',
    'ﬁ ① Ⅻ ＡＢＣ — “comillas” «españolas» …',
    'emoji 🙂 y 中文 mezclados',
]
cases = [{'text': s, 'ids': rt.encode_text(s)} for s in strings]
json.dump({'what': 'SentencePiece ids of tokenizer.model of OpenMOSS-Team/MOSS-TTS-Nano-100M-ONNX (sentencepiece, as onnx_tts_runtime encodes)', 'cases': cases},
          open(f'{fix_out}/moss-spm-ids.json', 'w'), ensure_ascii=False)

# 3. Rows and the first frames with a known stream of uniform numbers.
seed = 7
text = 'Hola, soy Elffuss. Hoy hace un día estupendo en Zaragoza.'
ids = rt.encode_text(text)
rows = rt.build_voice_clone_request_rows(codes, ids)
rt.rng = Xoshiro(seed)
rt.manifest['generation_defaults']['max_new_frames'] = 24
frames = rt.generate_audio_frames(rows)
json.dump({'what': 'Request rows and the first 24 frames of onnx_tts_runtime (sample_mode fixed) for the text with the voice prompt above, drawing its uniform numbers from createRng(seed).uniform of sdk/audio/rng.js',
           'manifest': {'tts_config': rt.manifest['tts_config'], 'prompt_templates': rt.manifest['prompt_templates']},
           'text': text, 'seed': seed, 'voice': name, 'ids': ids,
           'rows': len(rows['inputIds']), 'rowsSha256': hashlib.sha256(np.asarray(rows['inputIds'], dtype=np.int32).tobytes()).hexdigest(),
           'frames': frames},
          open(f'{fix_out}/moss-frames.json', 'w'))
print('rows', len(rows['inputIds']), 'frames', len(frames))
