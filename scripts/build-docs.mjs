// Generates the documentation from its single sources, never by hand:
//   docs/api/<module>.md   from the JSDoc of sdk/<module>/*.js (exported functions,
//                          classes with their public members, constants, typedefs)
//   docs/MODELS.md         from registry/tasks.json
