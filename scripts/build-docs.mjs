//   docs/README.md         the index, with the module table
//   README.md              the module table between its markers
//
//   node scripts/build-docs.mjs            write
//   node scripts/build-docs.mjs --check    compare with what is committed (exit 1 on any difference)
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { sites as readSites, siteUrl } from '../deploy/sites.mjs';
import { mergeStrings } from './build.mjs';
import { repoPage } from '../sdk/core/hub-url.js';
import { formatMB } from './lib/pages.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const GEN = '<!-- GENERATED by scripts/build-docs.mjs. Do not edit. -->\n';

/** Parse one JSDoc block body into description and tags. */
export function parseJsDoc(body) {
  const lines = body.split('\n').map(l => l.replace(/^\s*\*\s?/, '')).filter((l, i, a) => !(i === 0 && !l.trim()));
  const desc = [];
  const tags = [];
  for (const l of lines) {
    const m = /^@(\w+)\s*(.*)$/.exec(l.trim());
    if (m) tags.push({ tag: m[1], text: m[2] });
    else if (tags.length) tags[tags.length - 1].text += (tags[tags.length - 1].text ? ' ' : '') + l.trim();
    else desc.push(l);
  }
  return { description: desc.join('\n').trim(), tags };
}

/** Split `{type} name rest` of a @param, @returns or @typedef tag (types may nest braces). */
export function typed(text) {
  let type = '', rest = text.trim();
  if (rest.startsWith('{')) {
    let depth = 0, i = 0;
    for (; i < rest.length; i++) {
      if (rest[i] === '{') depth++;
      else if (rest[i] === '}' && --depth === 0) break;
    }
    type = rest.slice(1, i).trim();
    rest = rest.slice(i + 1).trim();
  }
  const n = /^(\[?[\w.$]+(?:=[^\]]*)?\]?)\s*(?:-\s*)?([\s\S]*)$/.exec(rest);
  return { type, name: n ? n[1] : '', text: n ? n[2].trim() : rest };
}

/** The parameter list of a signature line, with nested parentheses (default values). */
function paramsOf(line, from) {
  const start = line.indexOf('(', from);
  if (start < 0) return '';
  let depth = 0;
  for (let i = start; i < line.length; i++) {
    if (line[i] === '(') depth++;
    else if (line[i] === ')' && --depth === 0) return line.slice(start + 1, i).trim();
  }
  return line.slice(start + 1).trim() + ' …';
}

/** Exported API of one module file, from its JSDoc. */
export function extract(source) {
  const out = [];
  const re = /\/\*\*([\s\S]*?)\*\/\s*\n([^\n]*)/g;
  let m;
  let inClass = null;
  while ((m = re.exec(source))) {
    const doc = parseJsDoc(m[1]);
    const line = m[2];
    let d;
    if ((d = /^export\s+(async\s+)?function\s*\*?\s*(\w+)\s*\(/.exec(line))) { out.push({ kind: 'function', name: d[2], params: paramsOf(line, d.index + d[0].length - 1), ...doc }); inClass = null; }
    else if ((d = /^export\s+class\s+(\w+)/.exec(line))) { inClass = { kind: 'class', name: d[1], members: [], ...doc }; out.push(inClass); }
    else if ((d = /^export\s+const\s+(\w+)/.exec(line))) { out.push({ kind: 'const', name: d[1], ...doc }); inClass = null; }
    else if (inClass && (d = /^\s{2}(static\s+)?(async\s+)?(get\s+|set\s+)?([a-zA-Z]\w*)\s*\(/.exec(line))) inClass.members.push({ name: d[4], accessor: (d[3] || '').trim(), params: paramsOf(line, d.index + d[0].length - 1), ...doc });
    else if (!line.trim() || /^\s*\/\//.test(line)) { /* a block before a comment: no export */ }
    for (const tag of doc.tags.filter(x => x.tag === 'typedef')) {
      const td = typed(tag.text);
      out.push({ kind: 'typedef', name: td.name, type: td.type, description: td.text || '' });
    }
  }
  return out;
}

const mdEscape = s => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

function renderEntry(e) {
  const lines = [];
  if (e.kind === 'typedef') {
    lines.push(`### Type \`${e.name}\``, '', '```ts', e.type.replace(/\s+/g, ' ').trim(), '```');
    if (e.description) lines.push('', e.description);
    return lines.join('\n');
  }
  const sig = e.kind === 'function' ? `${e.name}(${e.params.replace(/\s+/g, ' ')})` : e.kind === 'class' ? `class ${e.name}` : e.name;
  lines.push(`### \`${sig}\``);
  if (e.description) lines.push('', e.description);
  const params = e.tags?.filter(t => t.tag === 'param').map(t => typed(t.text)) || [];
  if (params.length) {
    lines.push('', '| Parameter | Type | |', '|---|---|---|');
    for (const p of params) lines.push(`| \`${mdEscape(p.name)}\` | \`${mdEscape(p.type)}\` | ${mdEscape(p.text)} |`);
  }
  const ret = e.tags?.find(t => t.tag === 'returns' || t.tag === 'return');
  if (ret) { const r = typed(ret.text); lines.push('', `Returns \`${mdEscape(r.type)}\`${r.name || r.text ? ': ' + [r.name, r.text].filter(Boolean).join(' ') : '.'}`); }
  if (e.kind === 'class' && e.members.length) {
    lines.push('');
    for (const mb of e.members) {
      const s = mb.accessor === 'get' ? `.${mb.name}` : `.${mb.name}(${mb.params.replace(/\s+/g, ' ')})`;
      lines.push(`- \`${s}\`${mb.description ? ': ' + mb.description.replace(/\n/g, ' ') : ''}`);
    }
  }
  return lines.join('\n');
}

/** docs/api/<module>.md for every directory of sdk/. */
export function apiDocs(root = ROOT) {
  const out = new Map();
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  for (const mod of readdirSync(join(root, 'sdk')).sort()) {
    const dir = join(root, 'sdk', mod);
    const files = readdirSync(dir).filter(f => f.endsWith('.js') && !f.startsWith('._')).sort();
    const sections = [];
    for (const f of files) {
      const src = readFileSync(join(dir, f), 'utf8');
      const head = /^(?:\/\/[^\n]*\n)+/.exec(src)?.[0].split('\n').map(l => l.replace(/^\/\/ ?/, '')).filter(l => !/SPDX|Copyright|^Portions|^\s{2}/.test(l)).join('\n').trim() || '';
      const entries = extract(src);
      if (!entries.length) continue;
      sections.push(`## \`sdk/${mod}/${f}\`\n\n${head ? head.replace(/\n(?!\n)/g, ' ').replace(/ {2,}/g, ' ') + '\n\n' : ''}${entries.map(renderEntry).join('\n\n')}`);
    }
    const entry = Object.entries(pkg.exports).filter(([k]) => k === `./${mod}` || k.startsWith(`./${mod}/`)).map(([k]) => '`@elffuss/ai' + k.slice(1) + '`').join(', ');
    out.set(`docs/api/${mod}.md`, `${GEN}# ${mod}\n\n${entry ? `Imported as ${entry}.\n\n` : ''}${sections.join('\n\n')}\n`);
  }
  return out;
}

/** The module table: every package entry and what it is today. */
export function moduleTable(root = ROOT) {
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const reg = JSON.parse(readFileSync(join(root, 'registry', 'tasks.json'), 'utf8'));
  const apps = readSites(root).filter(s => !s.catalog);
  const rows = ['| Module | What it does | Site | Status |', '|---|---|---|---|'];
  rows.push('| `@elffuss/ai/core` | Model store client, backend choice, pinned runtimes, registry, Worker host, errors, progress | every site | in use |');
  for (const task of Object.keys(reg.tasks)) {
    const site = apps.find(s => s.task === task);
    const what = { 'remove-bg': 'Remove the background of an image (transparent PNG)', depth: 'Depth map of a photo', detect: 'Object detection, 80 COCO classes', ocr: 'Text from images and PDFs' }[task] || task;
    const has = existsSync(join(root, 'sdk', task, 'index.js')) && pkg.exports[`./${task}`];
    rows.push(`| \`@elffuss/ai/${task}\` | ${what} | ${site ? `[${site.host}](https://${site.host}/)` : ''} | ${has ? 'in use' : 'to be written (`./' + task + '/sizes` exists)'} |`);
  }
  return rows.join('\n');
}

/** docs/MODELS.md from the registry. */
export function modelsDoc(root = ROOT) {
  const reg = JSON.parse(readFileSync(join(root, 'registry', 'tasks.json'), 'utf8'));
  const out = [GEN, '# Models', '', 'Every model a site downloads, from its original Hugging Face repository, pinned to a commit. Nothing here is hosted or redistributed by Elffuss: the model store of the sites downloads each file once per browser and checks its hash. Generated from `registry/tasks.json`.', ''];
  out.push('| Task | Model | Base model | Licence | Backend · variant · download |', '|---|---|---|---|---|');
  for (const [id, m] of Object.entries(reg.models)) {
    const variants = Object.entries(m.devices).flatMap(([dev, vs]) => vs.map(v => `${dev === 'webgpu' ? 'WebGPU' : 'WASM'} ${v.dtype}${v.when ? ' (with ' + v.when + ')' : ''} · ${formatMB(v.bytes, 'en')} MB`));
    out.push(`| ${m.task} | \`${id}\` | [${m.base.name}](${m.base.url}), by ${m.base.author} | ${m.license} (base: ${m.base.license}) | ${variants.join('<br>')} |`);
  }
  out.push('');
  for (const [id, m] of Object.entries(reg.models)) {
    out.push(`## \`${id}\``, '');
    out.push(`- Base model: [${m.base.name}](${m.base.url}), by ${m.base.author}, ${m.base.license}.`);
    for (const [pn, p] of Object.entries(m.parts)) out.push(`- ${Object.keys(m.parts).length > 1 ? `Part \`${pn}\`: ` : 'Weights: '}[${p.repo}](${repoPage(p.repo, p.revision)}) at \`${p.revision}\`, ${p.license}.`);
    if (m.notes?.en) out.push(`- Note: ${m.notes.en}`);
    out.push('', '| Backend | Variant | Files | Download |', '|---|---|---|---|');
    for (const [dev, vs] of Object.entries(m.devices)) for (const v of vs) out.push(`| ${dev === 'webgpu' ? 'WebGPU' : 'WASM'} | ${v.dtype}${v.when ? ' (' + v.when + ')' : ''} | ${v.files.map(f => '`' + f + '`').join(', ')} | ${formatMB(v.bytes, 'en')} MB |`);
    out.push('');
  }
  return out.join('\n');
}

/** docs/llms.txt (llmstxt.org): what the sites and modules are, in plain words. */
export function llmsTxt(root = ROOT) {
  const reg = JSON.parse(readFileSync(join(root, 'registry', 'tasks.json'), 'utf8'));
  const sites = readSites(root);
  const lines = ['# Elffuss tools', '', '> Small tools that run in the browser: remove the background of a photo, read the text of images and PDFs, detect objects, and make depth maps. Each runs its model in the browser with WebGPU or WebAssembly; the only download is the model, from its original Hugging Face repository at a pinned revision, and it is kept in the browser for the next visit. Files the user opens never leave the device.', ''];
  lines.push('## Tools', '');
  for (const s of sites.filter(x => !x.catalog)) {
    const t = mergeStrings(root, s.dir).en;
    const m = reg.models[s.models[0]];
    const sizes = Object.values(m.devices).flat().map(v => v.bytes);
    const size = Math.min(...sizes) === Math.max(...sizes) ? `${formatMB(sizes[0], 'en')} MB` : `${formatMB(Math.min(...sizes), 'en')} to ${formatMB(Math.max(...sizes), 'en')} MB`;
    lines.push(`- [${t['catalog.name']}](${siteUrl(s, 'pro')}en/): ${t['catalog.line']} Model: ${m.base.name} by ${m.base.author} (${m.base.license}). Download: ${size}, once per browser.`);
  }
  const cat = sites.find(x => x.catalog);
  lines.push(`- [Every tool](${siteUrl(cat, 'pro')}en/): the catalog.`, '');
  lines.push('## Modules', '', '- `@elffuss/ai/core`: the pieces the tools share (model store client, backend choice, pinned runtimes, model registry, errors with codes).');
  for (const task of Object.keys(reg.tasks)) lines.push(`- \`@elffuss/ai/${task}\` and \`@elffuss/ai/${task}/sizes\`: the ${task} task and the download size of each of its variants.`);
  lines.push('', '## Notes', '', '- The weights are not hosted by Elffuss: each tool names its model, author and licence on its page.', '- Without the Elffuss model store (models.elffuss.com) a tool downloads nothing and says so.', '');
  return lines.join('\n');
}

/** docs/README.md, the index of the documentation. */
export function docsIndex(root = ROOT) {
  const api = [...apiDocs(root).keys()].map(p => `- [\`${p.slice('docs/api/'.length, -3)}\`](${p.slice('docs/'.length)})`).join('\n');
  return `${GEN}# Documentation

## Modules

${moduleTable(root)}

## API reference

Generated from the JSDoc of \`sdk/\`.

${api}

## Also here

- [MODELS.md](MODELS.md): every model, its licence, its pinned revision and the download of each variant.
- [app-contract.md](app-contract.md): what a tool site and its task module must implement.
- [llms.txt](llms.txt): the tools and modules in plain words, for language models.
`;
}

/** The README with its module table refreshed between the markers. */
export function readmeWithTable(root = ROOT) {
  const p = join(root, 'README.md');
  const text = readFileSync(p, 'utf8');
  const a = '<!-- modules:start -->', b = '<!-- modules:end -->';
  if (!text.includes(a) || !text.includes(b)) return text;
  return text.slice(0, text.indexOf(a) + a.length) + '\n' + moduleTable(root) + '\n' + text.slice(text.indexOf(b));
}

export function generate(root = ROOT) {
  const files = new Map(apiDocs(root));
  files.set('docs/MODELS.md', modelsDoc(root));
  files.set('docs/llms.txt', llmsTxt(root));
  files.set('docs/README.md', docsIndex(root));
  files.set('README.md', readmeWithTable(root));
  return files;
}

function main(argv) {
  const files = generate();
  if (argv.includes('--check')) {
    let diff = 0;
    for (const [p, text] of files) {
      const f = join(ROOT, p);
      if (!existsSync(f) || readFileSync(f, 'utf8') !== text) { console.log(`✗ ${p} is not what the sources give (run node scripts/build-docs.mjs)`); diff++; }
    }
    console.log(diff ? `docs: ${diff} files differ` : `docs: ${files.size} generated files match their sources`);
    return diff ? 1 : 0;
  }
  for (const [p, text] of files) { mkdirSync(dirname(join(ROOT, p)), { recursive: true }); writeFileSync(join(ROOT, p), text); }
  console.log(`docs: ${files.size} files written`);
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exitCode = main(process.argv.slice(2));
